/**
 * 生成内联 SVG 图标
 * @param {string} name 图标名（ICONS 的键）
 * @returns {string} svg HTML（Astro 组件中需经 set:html 插入）
 */
export function icon(name) {
  return `<svg class="og-icon" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${ICONS[name] || ''}</svg>`;
}

/** HTML 转义（所有插值进 innerHTML 前必须经过） */
export function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, (c) => ({
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#39;'
  })[c]);
}
